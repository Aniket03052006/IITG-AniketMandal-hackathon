"""Event -> scenario, deterministically.

The template of an event class is its catalog scenario (configs/scenarios.yaml, magnitudes untouched) plus sector shocks propagated from the active risk
factors through the transmission table. Nothing is learned or generated by a model: the same event, portfolio and configuration always give the same
scenario, and its version is a hash of its shocks, so an adjusted value is a different scenario with a different run id.

A generated scenario is a SIMULATION, never a prediction. When no defensible scenario exists the answer is SCENARIO UNAVAILABLE with the reason.
"""

from __future__ import annotations

import hashlib
import json
from collections import defaultdict

from ..adjust.models import AdjustmentNotice
from ..config import StressConfig
from ..domain import AssetClass, EventCategory, Portfolio, RiskFactor, Scenario, ShockScope, ShockSpec
from ..intelligence.model import Availability
from ..stress.history_check import ShockHistory
from ..stress.scenarios import ScenarioCatalog
from .config import PropagationConfig, level_rank
from .mapping import PropagationMapper
from .models import (
    SCENARIO_LABEL,
    Gate,
    GeneratedScenario,
    PortfolioMateriality,
    PropagationGraph,
    ShockOrigin,
    Status,
)

SOFT = ("direction", "severity", "materiality")  # gates a what-if may bypass; the others are structural


class ScenarioGenerator:
    def __init__(self, cfg: PropagationConfig, catalog: ScenarioCatalog, stress_cfg: StressConfig, history: ShockHistory | None = None) -> None:
        self.cfg = cfg
        self._catalog = catalog
        self._stress = stress_cfg
        self._history = history

    def generate(self, *, signal_id: str, portfolio: Portfolio, graph: PropagationGraph, materiality: PortfolioMateriality, category: EventCategory | None,
                 severity: float | None, direction: str | None, event_sector: str | None, issuer_known: bool, mapper: PropagationMapper,
                 adjustments: AdjustmentNotice | None = None) -> GeneratedScenario:
        gen = self.cfg.generation
        gates: list[Gate] = []

        def unavailable(reason: str, *, template: str | None = None, label: str | None = None) -> GeneratedScenario:
            return GeneratedScenario(signal_id=signal_id, availability=Availability.UNAVAILABLE, reason=reason, template=template, template_label=label, gates=gates,
                                     scenario=None, origins=[], portfolio_id=portfolio.portfolio_id, adjustments=adjustments)

        gates.append(Gate(id="event", label="The text describes a market event", passed=category is not None,
                          detail=category.value.replace("_", " ").lower() if category else "no event class (the text is not read as a market event)"))
        if category is None:
            return unavailable("SCENARIO UNAVAILABLE: the text is not read as a market event, so no scenario template applies.")
        tpl = self.cfg.templates[category]
        base = self._catalog.default_for(category)
        gates.append(Gate(id="template", label="A scenario template exists for this class", passed=tpl.enabled and base is not None,
                          detail=(f"template “{tpl.label}”" if tpl.enabled and base is not None else "the template is switched off" if base is not None else "the catalog has no scenario for this class")))
        if not tpl.enabled or base is None:
            return unavailable(f"SCENARIO UNAVAILABLE: no scenario template is available for {category.value.replace('_', ' ').lower()} events.",
                               template=category.value, label=tpl.label)
        gates.append(Gate(id="mapping", label="A defensible mapping from the event to the portfolio exists",
                          passed=graph.availability is Availability.AVAILABLE and bool(graph.reached),
                          detail=(f"{len(graph.reached)} holdings are reached ({graph.reached_share:.1%} of the book)" if graph.reached else graph.reason or "nothing is reached")))
        if not (graph.availability is Availability.AVAILABLE and graph.reached):
            return unavailable("SCENARIO UNAVAILABLE: " + (graph.reason or "the book holds nothing the event reaches."), template=category.value, label=tpl.label)

        favourable = direction == "favourable"
        gates.append(Gate(id="direction", label="The event is not favourable", passed=not (gen.downside_only and favourable),
                          detail="a loss scenario is generated for adverse, mixed or neutral events" if not favourable else "the event reads as favourable; EventShock generates downside simulations only"))
        gates.append(Gate(id="severity", label=f"Severity at least {gen.min_severity:g}", passed=severity is not None and severity >= gen.min_severity,
                          detail="severity not assessed" if severity is None else f"severity {severity:g}"))
        gates.append(Gate(id="materiality", label=f"Relevance at least {gen.min_materiality}",
                          passed=materiality.level in ("LOW", "MEDIUM", "HIGH", "CRITICAL") and level_rank(materiality.level) >= level_rank(gen.min_materiality),
                          detail=f"relevance {materiality.level}"))

        scenario, origins = self._build(base, category, tpl, graph, portfolio, event_sector, mapper)
        if scenario is None:
            gates.append(Gate(id="reach", label="At least one shock reaches your holdings", passed=False, detail="no shock of the scenario binds to this event and these holdings"))
            return unavailable("SCENARIO UNAVAILABLE: no shock of the template reaches what this event is about and what you hold.", template=category.value, label=tpl.label)
        binds = any(self._binds(s, issuer_known, event_sector) for s in scenario.shocks)
        gates.append(Gate(id="reach", label="At least one shock reaches your holdings", passed=binds,
                          detail=f"{sum(1 for s in scenario.shocks if self._binds(s, issuer_known, event_sector))} of {len(scenario.shocks)} shocks bind to this event"))
        if not binds:
            return unavailable("SCENARIO UNAVAILABLE: no shock of the template reaches what this event is about.", template=category.value, label=tpl.label)

        failed = [g for g in gates if not g.passed]
        history = None
        if self._history is not None:
            ref = scenario.reference_impact
            used = severity if severity is not None else ref
            scale = min(max(used / ref, self._stress.severity_scale_min), self._stress.severity_scale_max)
            history = self._history.check_scenario(scenario, severity_scale=scale)
        if failed:
            return GeneratedScenario(
                signal_id=signal_id, availability=Availability.ABSTAINED, can_force=all(g.id in SOFT for g in failed),
                reason="SCENARIO UNAVAILABLE: " + "; ".join(f"{g.label} ({g.detail})" for g in failed) + ". It can be run as a what-if.",
                template=category.value, template_label=tpl.label, gates=gates, scenario=scenario, origins=origins, history_check=history,
                portfolio_id=portfolio.portfolio_id, adjustments=adjustments)
        return GeneratedScenario(signal_id=signal_id, availability=Availability.AVAILABLE, template=category.value, template_label=tpl.label, gates=gates,
                                 scenario=scenario, origins=origins, history_check=history, portfolio_id=portfolio.portfolio_id, adjustments=adjustments)

    @staticmethod
    def _binds(s: ShockSpec, issuer_known: bool, event_sector: str | None) -> bool:
        if s.scope is ShockScope.MARKET:
            return True
        if s.scope is ShockScope.SECTOR:
            return bool(s.sector or event_sector)
        return issuer_known

    # ----------------------------------------------------------------------------------------------------------------- build
    def _build(self, base: Scenario, category: EventCategory, tpl, graph: PropagationGraph, portfolio: Portfolio, event_sector: str | None,  # noqa: ANN001
               mapper: PropagationMapper) -> tuple[Scenario | None, list[ShockOrigin]]:
        gen = self.cfg.generation
        shocks: list[ShockSpec] = []
        origins: list[ShockOrigin] = []
        market: dict[RiskFactor, float] = {}
        for sh in base.shocks:
            key = f"{sh.factor.value}:{sh.scope.value}"
            if key in tpl.shock_overrides:
                value, source, status, basis = tpl.shock_overrides[key], "USER", Status.USER_ASSUMPTION, f"size set by you (the catalog says {sh.value:g})"
            else:
                value, source, status, basis = sh.value, "CATALOG_BASE", Status.SCENARIO_ASSUMPTION, f"catalog scenario “{base.name}”: {sh.rationale}"
            shocks.append(ShockSpec(factor=sh.factor, scope=sh.scope, value=value, rationale=sh.rationale))
            origins.append(ShockOrigin(factor=sh.factor.value, scope=sh.scope.value, sector=None, source=source, risk_factor=None, status=status, base_value=value, basis=basis))
            if sh.scope is ShockScope.MARKET:
                market[sh.factor] = value

        # sector shocks propagated from the active risk factors through the transmission table
        held_value: dict[str, float] = defaultdict(float)
        for a in portfolio.assets:
            if a.asset_type not in (AssetClass.CASH, AssetClass.OTHER):
                held_value[a.sector] += a.market_value
        edge_status = {e.rule_id: e.status for e in graph.edges}
        scale = gen.propagation_scale * tpl.propagation_scale
        per_sector: dict[str, list[tuple[str, str, float]]] = defaultdict(list)
        for f in graph.active_factors:
            for eid, edge in self.cfg.risk_factors[f.id].transmission.items():
                if edge.enabled and edge.shock and edge.kind == "SECTOR" and edge.key in held_value and edge.key != event_sector:
                    per_sector[edge.key].append((f.id, eid, edge.weight * scale))
        ranked = sorted(per_sector, key=lambda s: (-held_value[s], s))[: gen.max_propagated_sectors]
        for sector in sorted(ranked):
            contrib = per_sector[sector]
            w = max(-1.0, min(1.0, sum(c[2] for c in contrib)))
            if w == 0:
                continue
            via = ", ".join(f"{self.cfg.risk_factors[r].label} ({e})" for r, e, _ in contrib)
            user = any(edge_status.get(f"risk_factors.{r}.transmission.{e}") is Status.USER_ASSUMPTION for r, e, _ in contrib)
            status = Status.USER_ASSUMPTION if user else Status.SCENARIO_ASSUMPTION
            eq = max(-1.0, min(1.0, market.get(RiskFactor.EQUITY, 0.0) + gen.propagated_equity_shock * w))
            shocks.append(ShockSpec(factor=RiskFactor.EQUITY, scope=ShockScope.SECTOR, sector=sector, value=round(eq, 6),
                                    rationale=f"Propagated to {sector} via {via}: the market-wide equity shock plus {gen.propagated_equity_shock * w:+.4f} (weight {w:+.2f})."))
            origins.append(ShockOrigin(factor="EQUITY", scope="SECTOR", sector=sector, source="PROPAGATED", risk_factor=contrib[0][0], status=status, base_value=round(eq, 6),
                                       basis=f"transmission {via}; weight {w:+.2f}; replaces the market-wide equity shock for {sector} (the engine applies the most specific shock)"))
            if w > 0 and gen.propagated_spread_bps > 0:
                sp = round(market.get(RiskFactor.CREDIT_SPREAD_BPS, 0.0) + gen.propagated_spread_bps * w, 6)
                shocks.append(ShockSpec(factor=RiskFactor.CREDIT_SPREAD_BPS, scope=ShockScope.SECTOR, sector=sector, value=sp,
                                        rationale=f"Propagated to {sector} via {via}: the market-wide spread shock plus {gen.propagated_spread_bps * w:+.0f} bp."))
                origins.append(ShockOrigin(factor="CREDIT_SPREAD_BPS", scope="SECTOR", sector=sector, source="PROPAGATED", risk_factor=contrib[0][0], status=status, base_value=sp,
                                           basis=f"transmission {via}; weight {w:+.2f}; replaces the market-wide spread shock for {sector}"))
        if not shocks:
            return None, []
        digest = hashlib.sha256(json.dumps([[s.factor.value, s.scope.value, s.sector, round(s.value, 8)] for s in shocks] + [base.id, base.version],
                                           sort_keys=True).encode()).hexdigest()
        scenario = Scenario(
            id=f"gen_{category.value.lower()}_{digest[:8]}", version=f"gen-{digest[8:18]}", name=f"{tpl.label}, generated for this event", category=category,
            description=f"{SCENARIO_LABEL}. Base: the catalog scenario “{base.name}”, plus propagated sector shocks.", illustrative=True,
            reference_impact=base.reference_impact, shocks=shocks)
        return scenario, origins

